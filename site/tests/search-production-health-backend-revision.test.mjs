import assert from 'node:assert/strict';
import { mkdtemp, mkdir, readFile, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import test from 'node:test';

import {
  computeEventSearchRevision,
  renderEventSearchRevisionModule,
  verifyEventSearchRevision,
} from '../../scripts/generate_event_search_revision.mjs';

const digest = /^sha256:[0-9a-f]{64}$/u;

test('event-search revision digest is path/content deterministic and excludes tests/generated output', async () => {
  const root = await mkdtemp(join(tmpdir(), 'event-search-revision-'));
  await mkdir(join(root, 'nested'));
  await writeFile(join(root, 'index.ts'), 'export const value = 1;\n');
  await writeFile(join(root, 'nested/module.ts'), 'export const nested = true;\n');
  await writeFile(join(root, 'ignored.test.mjs'), 'must not affect deployed digest\n');
  await writeFile(join(root, 'search-backend-revision.generated.ts'), 'stale generated bytes\n');
  const first = await computeEventSearchRevision(root);
  assert.match(first.revision, digest);
  assert.deepEqual(first.files, ['index.ts', 'nested/module.ts']);
  await writeFile(join(root, 'ignored.test.mjs'), 'changed test bytes\n');
  await writeFile(join(root, 'search-backend-revision.generated.ts'), 'changed generated bytes\n');
  assert.equal((await computeEventSearchRevision(root)).revision, first.revision);
  await writeFile(join(root, 'nested/module.ts'), 'export const nested = false;\n');
  assert.notEqual((await computeEventSearchRevision(root)).revision, first.revision);
});

test('committed event-search revision module exactly matches current deployable source tree', async () => {
  const sourceRoot = new URL('../../supabase/functions/event-search/', import.meta.url);
  const generated = new URL('../../supabase/functions/event-search/search-backend-revision.generated.ts', import.meta.url);
  const computed = await computeEventSearchRevision(sourceRoot);
  assert.match(computed.revision, digest);
  assert.equal(await readFile(generated, 'utf8'), renderEventSearchRevisionModule(computed));
  assert.equal((await verifyEventSearchRevision({ sourceRoot, generated })).revision, computed.revision);
});
